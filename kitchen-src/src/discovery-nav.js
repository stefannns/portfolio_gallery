// Rows run from minZ toward +Z; columns run from minX toward +X.
// Require all four surrounding samples so movement between grid centers stays conservative.
export function isDiscoveryFloor(x, z) {
  if (!Number.isFinite(x) || !Number.isFinite(z)) return false;
  const gx = (x - DISCOVERY_NAV.minX) / DISCOVERY_NAV.step;
  const gz = (z - DISCOVERY_NAV.minZ) / DISCOVERY_NAV.step;
  const x0 = Math.floor(gx + 1e-8), x1 = Math.ceil(gx - 1e-8);
  const z0 = Math.floor(gz + 1e-8), z1 = Math.ceil(gz - 1e-8);
  if (x0 < 0 || z0 < 0 || x1 >= DISCOVERY_NAV.width || z1 >= DISCOVERY_NAV.height) return false;
  return DISCOVERY_NAV.rows[z0][x0] === '1' && DISCOVERY_NAV.rows[z0][x1] === '1'
    && DISCOVERY_NAV.rows[z1][x0] === '1' && DISCOVERY_NAV.rows[z1][x1] === '1';
}
